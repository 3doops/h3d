    def tflags(self, z: int) -> list[int]:
        out = []
        for y in range(self.size):
            for x in range(self.size):
                i = self.idx(x, y)
                f = self.mirror[z][i]
                tt = self.terrain[z][i]
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    if self.inside(x + dx, y + dy) and (self.terrain[z][self.idx(x + dx, y + dy)] == WATER) != (tt == WATER):
                        f |= 4
                        break
                oid = self.occ[z][i]
                if oid >= 0:
                    o = self.objects[oid]
                    if (x, y) in mask_cells(int(o["block"], 16), o["x"], o["y"]):
                        f |= 8
                    if (x, y) in mask_cells(int(o["visit"], 16), o["x"], o["y"]):
                        f |= 16
                out.append(f)
        return out

    def public_obj(self, o: dict) -> dict:
        return {k: v for k, v in o.items() if k in ("id", "type", "subtype", "def", "x", "y", "z", "block", "visit", "owner", "count", "town", "trigger", "underlay")}

    def public_town(self, t: dict) -> dict:
        return {k: v for k, v in t.items() if k != "object"}

    def hello(self) -> dict:
        if self.snap_extra:
            return {"t": "hello", "proto": 0, "source": "mock",
                    "game": f"{self.snap_extra.get('game', 'HotA')} {self.snap_extra.get('file', '')} (mock replay)"}
        return {"t": "hello", "proto": 0, "source": "mock", "game": "HotA 1.x (mock)"}

    def snapshot(self) -> dict:
        return {"t": "snapshot",
                "map": {"size": self.size, "levels": self.levels, "terrain": self.terrain, "terrain_frame": self.frame,
                        "river": self.river, "road": self.road, "tflags": [self.tflags(z) for z in range(self.levels)]},
                "fog": self.fog,
                "objects": [self.public_obj(o) for o in self.objects.values()],
                "heroes": list(self.heroes.values()), "towns": [self.public_town(t) for t in self.towns.values()],
                "players": self.players, "date": dict(self.date), "current": self.current, "me": self.me}

    def state(self, **kw) -> dict:
        msg = {"t": "state", "objects_changed": [], "objects_removed": [], "heroes": list(self.heroes.values()),
               "towns": [self.public_town(t) for t in self.towns.values()], "players": self.players,
               "date": dict(self.date), "current": self.current, "fog_open": []}
        msg.update(kw)
        return msg

    # -- mock path finding (the real bridge asks the engine!) ---------------------------------------
    def passable(self, x, y, z, hero_id=None) -> bool:
        i = self.idx(x, y)
        if self.terrain[z][i] in (WATER, ROCK):
            return False
        if self.occ[z][i] >= 0:
            return False
        for h in self.heroes.values():
            if h["id"] != hero_id and (h["x"], h["y"], h["z"]) == (x, y, z):
                return False
        return True

    def visit_target(self, x, y, z):
        oid = self.occ[z][self.idx(x, y)]
        if oid < 0:
            return None
        o = self.objects[oid]
        if (x, y) in mask_cells(int(o["visit"], 16), o["x"], o["y"]):
            return o
        return None

    def step_cost(self, x, y, z, diag) -> int:
        i = self.idx(x, y)
        c = ROAD_COST.get(self.road[z][i]) or TERRAIN_COST.get(self.terrain[z][i], 100)
        return c * 141 // 100 if diag else c

    def find_path(self, hero: dict, to) -> list[list[int]]:
        tx, ty, tz = to
        sx, sy, sz = hero["x"], hero["y"], hero["z"]
        if tz != sz or not self.inside(tx, ty):
            return []
        target_obj = self.visit_target(tx, ty, tz)
        if not target_obj and not self.passable(tx, ty, tz, hero["id"]):
            return []
        dist = {(sx, sy): 0}
        prev = {}
        pq = [(0, sx, sy)]
        while pq:
            d, x, y = heapq.heappop(pq)
            if (x, y) == (tx, ty):
                break
            if d > dist.get((x, y), 1 << 60):
                continue
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    if not dx and not dy:
                        continue
                    nx, ny = x + dx, y + dy
                    if not self.inside(nx, ny):
                        continue
                    if (nx, ny) != (tx, ty) and not self.passable(nx, ny, sz, hero["id"]):
                        continue
                    if (nx, ny) == (tx, ty) and target_obj is None and not self.passable(nx, ny, sz, hero["id"]):
                        continue
                    nd = d + self.step_cost(nx, ny, sz, bool(dx and dy))
                    if nd < dist.get((nx, ny), 1 << 60):
                        dist[(nx, ny)] = nd
                        prev[(nx, ny)] = (x, y)
                        heapq.heappush(pq, (nd, nx, ny))
        if (tx, ty) not in dist:
            return []
        cells = []
        c = (tx, ty)
        while c != (sx, sy):
            cells.append([c[0], c[1], tz, dist[c]])
            c = prev[c]
        cells.reverse()
        return cells

    # -- protocol handling --------------------------------------------------------------------------
    def handle(self, msg: dict) -> list[tuple[str, dict]]:
        t = msg.get("t")
        try:
            if t == "get_snapshot":
                return [("self", self.snapshot())]
            if t == "path":
                return [("self", self.cmd_path(msg))]
            if t == "cmd":
                c = msg.get("cmd")
                done = ("all", {"t": "cmd_done", "cmd": c, "result": {}})
                if c == "move_hero":
                    out = self.cmd_move(msg)
                    return out + [done] if not any(o[1].get("t") == "error" for o in out) else out
                if c == "select_hero":
                    return [done]
                if c == "end_turn":
                    return self.cmd_end_turn() + [done]
                return [("self", {"t": "error", "msg": f"unknown cmd {c}"})]
            if t == "dialog_answer":
                return self.cmd_dialog_answer(msg)
            return [("self", {"t": "error", "msg": f"unknown message type {t}"})]
        except Exception as e:  # keep the server alive
            return [("self", {"t": "error", "msg": f"{type(e).__name__}: {e}"})]

    def _hero_of(self, msg):
        h = self.heroes.get(int(msg.get("hero", -1)))
        if not h:
            raise ValueError("no such hero")
        return h

    def cmd_path(self, msg):
        h = self._hero_of(msg)
        cells = self.find_path(h, msg["to"])
        reach = sum(1 for c in cells if c[3] <= h["mp"])
        return {"t": "path", "hero": h["id"], "cells": cells, "reachable": reach}

    def dialog(self, text, style="ok", options=None, action=None) -> dict:
        did = self.next_dialog
        self.next_dialog += 1
        self.dialogs[did] = {"action": action, "options": options or []}
        return {"t": "dialog", "id": did, "text": text, "style": style, "options": options or []}

    def cmd_move(self, msg):
        h = self._hero_of(msg)
        if h["owner"] != self.current:
            return [("self", {"t": "error", "msg": "not your turn"})]
        cells = self.find_path(h, msg["to"])
        if not cells:
            return [("self", {"t": "error", "msg": "no path"})]
        walk = [c for c in cells if c[3] <= h["mp"]]
        target = self.visit_target(*cells[-1][:3]) if len(walk) == len(cells) else None
        if target and target["type"] in (54,) and walk:   # fight from the adjacent cell
            walk = walk[:-1]
        if not walk and not target:
            return [("self", {"t": "error", "msg": "not enough movement points"})]
        moved = [[c[0], c[1], c[2]] for c in walk]
        out_after: list[tuple[str, dict]] = []
        removed, changed = [], []
        fog_open = []
        if walk:
            last = walk[-1]
            dx, dy = last[0] - (walk[-2][0] if len(walk) > 1 else h["x"]), last[1] - (walk[-2][1] if len(walk) > 1 else h["y"])
            h["dir"] = {(0, -1): 0, (1, -1): 1, (1, 0): 2, (1, 1): 3, (0, 1): 4, (-1, 1): 5, (-1, 0): 6, (-1, -1): 7}.get((dx, dy), h["dir"])
            h["mp"] -= last[3]
            if target is None or target["type"] == 54:
                h["x"], h["y"] = last[0], last[1]
            else:
                h["x"], h["y"] = last[0], last[1]
            if h["owner"] == self.me:
                for c in moved:
                    fog_open += self.open_fog(c[0], c[1], c[2], 6)
        if target:
            ot = target["type"]
            p = self.players[h["owner"]]
            if ot == 79:
                p["res"][target["subtype"]] += target.get("amount", 5)
                removed.append(self._remove(target))
            elif ot == 101:
                out_after.append(("all", self.dialog(
                    "Вы нашли старый сундук. Взять золото или раздать его крестьянам за опыт?", "choose",
                    [{"text": "1000 золота", "icon": "gold"}, {"text": "500 опыта", "icon": "exp"}],
                    {"kind": "chest", "hero": h["id"], "obj": target["id"]})))
            elif ot == 5:
                removed.append(self._remove(target))
                out_after.append(("all", self.dialog("Вы подобрали артефакт.", "ok")))
            elif ot == 53:
                target["owner"] = h["owner"]
                changed.append(self.public_obj(target))
                out_after.append(("all", self.dialog(
                    f"Шахта ({RES_NAMES[target['subtype']] if target['subtype'] < 7 else 'abandoned'}) теперь ваша.", "ok")))
            elif ot == 54:
                removed.append(self._remove(target))
                h["exp"] += 50 * target.get("count", 10)
                out_after.append(("all", {"t": "event", "kind": "battle", "attacker": h["id"],
                                          "defender": {"type": "monster", "id": target["subtype"], "count": target.get("count", 0)},
                                          "winner": "attacker", "losses": {"attacker": [[h["army"][0][0], 2]], "defender": "all"}}))
            elif ot == 98:
                town = next(t for t in self.towns.values() if t["object"] == target["id"])
                if town["owner"] != h["owner"]:
                    town["owner"] = h["owner"]
                    target["owner"] = h["owner"]
                    changed.append(self.public_obj(target))
                    out_after.append(("all", {"t": "event", "kind": "battle", "attacker": h["id"],
                                              "defender": {"type": "town", "id": town["id"]}, "winner": "attacker",
                                              "losses": {}}))
                out_after.append(("all", {"t": "event", "kind": "window", "name": "townScreen", "action": "closed"}))
            elif ot == 103:
                ex, ey, ez = self.gates[target["id"]]
                h["x"], h["y"], h["z"] = ex, ey, ez
                moved.append([ex, ey, ez])
                if h["owner"] == self.me:
                    fog_open += self.open_fog(ex, ey, ez, 7)
            elif ot == 12:
                p["res"][0] += 5
                p["res"][6] += 500
                removed.append(self._remove(target))
                out_after.append(("all", self.dialog("Брошенный лагерь: 5 дерева и 500 золота.", "ok")))
            elif ot in (88, 89, 90):
                out_after.append(("all", self.dialog("Изучить заклинание «Волшебная стрела»?", "yesno",
                                                     action={"kind": "shrine", "hero": h["id"]})))
            elif ot == 91:
                out_after.append(("all", self.dialog("Табличка: «На восток — Эльмшейд, на юг — Гримхоллоу».", "ok")))
            elif ot == 112:
                p["res"][4] += 3
                out_after.append(("all", self.dialog("Мельник отдаёт вам 3 кристалла.", "ok")))
            else:
                out_after.append(("all", {"t": "event", "kind": "window", "name": f"visit:{ot}", "action": "closed"}))
        out = [("all", {"t": "event", "kind": "hero_move", "hero": h["id"], "cells": moved}),
               ("all", self.state(objects_changed=changed, objects_removed=removed, fog_open=fog_open))]
        return out + out_after

    def _remove(self, o: dict) -> int:
        self.objects.pop(o["id"], None)
        for cx, cy in mask_cells(int(o["block"], 16) | int(o["visit"], 16), o["x"], o["y"]):
            if self.inside(cx, cy) and self.occ[o["z"]][self.idx(cx, cy)] == o["id"]:
                self.occ[o["z"]][self.idx(cx, cy)] = -1
        return o["id"]

    def cmd_dialog_answer(self, msg):
        d = self.dialogs.pop(int(msg.get("id", -1)), None)
        if d is None:
            return [("self", {"t": "error", "msg": "no such dialog"})]
        a = d["action"] or {}
        ans = int(msg.get("answer", 0))
        out = []
        if a.get("kind") == "chest":
            h = self.heroes[a["hero"]]
            if ans == 0:
                self.players[h["owner"]]["res"][6] += 1000
            else:
                h["exp"] += 500
            o = self.objects.get(a["obj"])
            removed = [self._remove(o)] if o else []
            out.append(("all", self.state(objects_removed=removed)))
        elif a.get("kind") == "shrine" and ans == 0:
            out.append(("all", self.dialog("Вы изучили «Волшебную стрелу».", "ok")))
        return out

    def cmd_end_turn(self):
        out = [("all", {"t": "event", "kind": "turn", "current": 1, "date": dict(self.date)})]
        self.current = 1
        # the "AI" moves its hero a couple of cells back and forth
        ai = self.heroes.get(3)
        if ai:
            dest = [ai["x"] + (2 if self.date["day"] % 2 else -2), ai["y"], ai["z"]]
            cells = self.find_path(ai, dest)
            if cells:
                ai["x"], ai["y"] = cells[-1][0], cells[-1][1]
                out.append(("all", {"t": "event", "kind": "hero_move", "hero": 3, "cells": [c[:3] for c in cells]}))
        self.current = 0
        d = self.date
        d["day"] += 1
        if d["day"] > 7:
            d["day"] = 1
            d["week"] += 1
            if d["week"] > 4:
                d["week"] = 1
                d["month"] += 1
        new_week = d["day"] == 1
        for h in self.heroes.values():
            h["mp"] = h["mp_max"]
        for p in self.players:
            p["res"][6] += 1000 + 500 * sum(1 for t in self.towns.values() if t["owner"] == p["id"])
            for o in self.objects.values():
                if o["type"] == 53 and o["owner"] == p["id"] and o["subtype"] < 7:
                    p["res"][o["subtype"]] += 2 if o["subtype"] in (0, 2) else 1
        out.append(("all", {"t": "event", "kind": "turn", "current": 0, "date": dict(d)}))
        out.append(("all", self.state()))
        if new_week:
            out.append(("all", self.dialog("Астрологи объявляют неделю Грифона! Прирост грифонов +5.", "ok")))
        return out


