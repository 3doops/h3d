async def serve(game: MockGame, host: str = "127.0.0.1", port: int = 8765, log=print):
    from websockets.asyncio.server import serve as ws_serve

    clients = set()

    async def send(ws, obj):
        await ws.send(json.dumps(obj, ensure_ascii=False, separators=(",", ":")))

    async def handler(ws):
        clients.add(ws)
        log(f"client connected {ws.remote_address}")
        try:
            await send(ws, game.hello())
            await send(ws, game.snapshot())
            async for raw in ws:
                try:
                    msg = json.loads(raw)
                except json.JSONDecodeError:
                    await send(ws, {"t": "error", "msg": "bad json"})
                    continue
                log(f"<- {raw[:200]}")
                for target, out in game.handle(msg):
                    log(f"-> {out.get('t')} {out.get('kind', '')}")
                    if target == "self":
                        await send(ws, out)
                    else:
                        for c in list(clients):
                            try:
                                await send(c, out)
                            except Exception:
                                pass
        except Exception as e:
            log(f"client error: {e}")
        finally:
            clients.discard(ws)
            log("client disconnected")

    # generous keepalive: a client may block for many seconds while it builds the 3D world
    async with ws_serve(handler, host, port, max_size=2 ** 24, ping_interval=60, ping_timeout=600):
        log(f"mock bridge on ws://{host}:{port}")
        await asyncio.Future()


def main(argv=None):
    ap = argparse.ArgumentParser(description="Mock HotA bridge (PROTOCOL.md v0)")
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--port", type=int, default=8765)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--reveal", action="store_true", help="no fog of war")
    ap.add_argument("--dump", help="write the snapshot JSON to this file and exit")
    ap.add_argument("--replay", help="use a recorded snapshot (map, objects, heroes) with the mock mechanics")
    ap.add_argument("--quiet", action="store_true")
    a = ap.parse_args(argv)
    game = MockGame.from_snapshot(a.replay, a.reveal) if a.replay else MockGame.create(a.seed, a.reveal)
    if a.dump:
        with open(a.dump, "w", encoding="utf-8") as f:
            json.dump(game.snapshot(), f, ensure_ascii=False)
        print(f"objects={len(game.objects)} heroes={len(game.heroes)} -> {a.dump}")
        return
    try:
        asyncio.run(serve(game, a.host, a.port, log=(lambda *_: None) if a.quiet else
                          (lambda *x: print(*x, flush=True))))
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    sys.exit(main())
