def masks_from_def(name: str) -> tuple[int, int]:
    _c, _s, passa, act = DEFS[name]
    block = visit = 0
    for i in range(48):
        bit = 8 * (5 - i // 8) + (7 - i % 8)
        if passa[i] == "0":
            block |= 1 << bit
        if act[i] == "1":
            visit |= 1 << bit
    return block, visit


def mask_cells(mask: int, x: int, y: int) -> list[tuple[int, int]]:
    out = []
    for b in range(48):
        if mask >> b & 1:
            out.append((x - 7 + b % 8, y - 5 + b // 8))
    return out


def _hash(ix: int, iy: int, seed: int) -> float:
    h = (ix * 374761393 + iy * 668265263 + seed * 2147483647) & 0xFFFFFFFF
    h = (h ^ (h >> 13)) * 1274126177 & 0xFFFFFFFF
    return ((h ^ (h >> 16)) & 0xFFFF) / 65535.0


def vnoise(x: float, y: float, seed: int) -> float:
    ix, iy = math.floor(x), math.floor(y)
    fx, fy = x - ix, y - iy
    fx, fy = fx * fx * (3 - 2 * fx), fy * fy * (3 - 2 * fy)
    a, b = _hash(ix, iy, seed), _hash(ix + 1, iy, seed)
    c, d = _hash(ix, iy + 1, seed), _hash(ix + 1, iy + 1, seed)
    return (a + (b - a) * fx) * (1 - fy) + (c + (d - c) * fx) * fy


def fbm(x: float, y: float, seed: int, octaves: int = 4) -> float:
    s, amp, tot = 0.0, 0.5, 0.0
    for o in range(octaves):
        s += amp * vnoise(x, y, seed + o * 17)
        tot += amp
        x, y, amp = x * 2.03, y * 2.03, amp * 0.5
    return s / tot  # 0..1


def trace(points: list[tuple[int, int]], rng: random.Random) -> list[tuple[int, int]]:
    """4-connected chain of cells through the given points (roads, rivers)."""
    out = [points[0]]
    x, y = points[0]
    last_axis = 0
    for tx, ty in points[1:]:
        while (x, y) != (tx, ty):
            dx, dy = tx - x, ty - y
            # keep going along the same axis for a while (no 1-cell staircases), follow the overall slope
            want_x = abs(dx) / (abs(dx) + abs(dy))
            if not dy:
                ax = 0
            elif not dx:
                ax = 1
            elif rng.random() < 0.6:
                ax = last_axis
            else:
                ax = 0 if rng.random() < want_x else 1
            if ax == 0:
                x += 1 if dx > 0 else -1
            else:
                y += 1 if dy > 0 else -1
            last_axis = ax
            out.append((x, y))
    return out


